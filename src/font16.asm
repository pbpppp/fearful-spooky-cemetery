; Шрифт 8x16 (CP866) для текста в графическом режиме.
; В ROM BIOS кириллицы нет, поэтому шрифт лежит отдельным сектором
; сразу за загрузочным, а загрузчик читает его через int 13h в 0500h.
; Глифы взяты из стандартного консольного шрифта cp866-8x16 (пакет kbd).
;
; Номер глифа = код символа CP866 - 80h, таблица занимает 32 ячейки
; (80h..9Fh). Цифры и '-' в этот диапазон не попадают, поэтому их глифы
; положены в свободные ячейки: 81h->0, 83h->1, 86h->2, 87h->3, 89h->4,
; 8Bh->5, 8Fh->6, 93h->7, 94h->8, 95h->9, 96h->'-'. Ячейка 98h пустая:
; пробел не рисуется, подложка заливается отдельно, до вывода строк.
;
; 32 глифа по 16 строк = ровно 512 байт, один сектор.

